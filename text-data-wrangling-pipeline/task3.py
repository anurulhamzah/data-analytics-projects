    ax.set_xscale('log')
    plt.title('Product Performance Quadrant Analysis')
    plt.xlabel('Number of Reviews (Log Scale)')
    plt.ylabel('Median Rating')
    plt.legend(title='Quadrant', bbox_to_anchor=(1.05, 1), loc=2)
